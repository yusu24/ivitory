/**
 * Merge invitation's custom_texts and opening_text with DEFAULT_CUSTOM_TEXTS
 */
export function getInvitationTexts(invitation) {
  const custom = invitation?.custom_texts && typeof invitation.custom_texts === 'object'
    ? invitation.custom_texts
    : {};

  const merged = { ...DEFAULT_CUSTOM_TEXTS };
  for (const key of Object.keys(DEFAULT_CUSTOM_TEXTS)) {
    // section_visibility is an object — merge it separately
    if (key === 'section_visibility') {
      if (custom.section_visibility && typeof custom.section_visibility === 'object') {
        merged.section_visibility = {
          ...DEFAULT_CUSTOM_TEXTS.section_visibility,
          ...custom.section_visibility,
        };
      }
      continue;
    }
    if (custom[key] !== undefined && custom[key] !== null && String(custom[key]).trim() !== '') {
      merged[key] = custom[key];
    }
  }

  // Keep top-level opening_text synchronized if provided
  if (
    (!custom.opening_text || String(custom.opening_text).trim() === '') &&
    invitation?.opening_text &&
    String(invitation.opening_text).trim() !== ''
  ) {
    merged.opening_text = invitation.opening_text;
  }

  return merged;
}

/**
 * Get section visibility flags for a given invitation.
 * Returns an object with boolean values for each toggleable section.
 * All sections default to true (visible) if not explicitly set to false.
 */
export function getSectionVisibility(invitation) {
  const custom = invitation?.custom_texts ?? {};
  const saved = custom.section_visibility ?? {};
  const defaults = DEFAULT_CUSTOM_TEXTS.section_visibility;
  const result = {};
  for (const key of Object.keys(defaults)) {
    result[key] = saved[key] !== false; // default true
  }
  return result;
}

/**
 * Get computed inline style & classes for a specific photo slot ('cover' | 'hero' | 'bride' | 'groom')
 */
export function getPhotoSlotConfig(invitation, slot) {
  const defaults = DEFAULT_PHOTO_SETTINGS[slot] || DEFAULT_PHOTO_SETTINGS.cover;
  const saved =
    invitation?.photo_settings &&
    typeof invitation.photo_settings === 'object' &&
    invitation.photo_settings[slot]
      ? invitation.photo_settings[slot]
      : {};

  const scale = Number(saved.scale ?? defaults.scale);
  const x = Number(saved.x ?? defaults.x);
  const y = Number(saved.y ?? defaults.y);
  const fit = saved.fit || defaults.fit;
  const grayscale = Boolean(saved.grayscale ?? defaults.grayscale);

  return {
    scale,
    x,
    y,
    fit,
    grayscale,
    style: {
      objectFit: fit,
      objectPosition: `${x}% ${y}%`,
      transform: `scale(${scale / 100})`,
      transformOrigin: `${x}% ${y}%`,
    },
    filterClass: grayscale ? 'filter grayscale contrast-115' : '',
  };
}
